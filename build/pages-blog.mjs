function toc(html) {
  const items = [...html.matchAll(/<h2 id="([^"]+)">(.+?)<\/h2>/g)];
  return `<aside class="toc"><h2>فهرست مطالب</h2><ol>${items.map(([, id, t]) => `<li><a href="#${id}">${t.replace(/<[^>]+>/g, '')}</a></li>`).join('')}</ol></aside>`;
}

